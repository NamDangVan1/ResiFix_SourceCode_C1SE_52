export function translateUiText(value: string, locale: AppLocale): string {
  if (locale === 'vi') return value;

  const leadingWhitespace = value.match(/^\s*/)?.[0] ?? '';
  const trailingWhitespace = value.match(/\s*$/)?.[0] ?? '';
  const end = value.length - trailingWhitespace.length;
  const content = value.slice(leadingWhitespace.length, end);
  const translated = EN_TRANSLATIONS[content];
  if (translated !== undefined) return `${leadingWhitespace}${translated}${trailingWhitespace}`;

  for (const [pattern, render] of DYNAMIC_MESSAGE_TRANSLATIONS) {
    const match = content.match(pattern);
    if (match) return `${leadingWhitespace}${render(match)}${trailingWhitespace}`;
  }

  return value;
}
